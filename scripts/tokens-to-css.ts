// Writes packages/client/src/tokens.css from packages/client/tokens.json, the design system's
// export. Run after replacing tokens.json: npm run tokens
import { readFileSync, writeFileSync } from 'node:fs';

type Themed = { dark: string; light: string };
type Token<V> = { name: string; value: V };
type TextStyle = { name: string; fontSize: string; lineHeight: string; fontWeight: number };
type Tokens = {
  color: { tokens: Token<Themed>[] };
  type: {
    families: Record<string, string>;
    groups: { family: string; styles: TextStyle[] }[];
  };
  spacing: { tokens: Token<string>[] };
  radius: { tokens: Token<string>[] };
  size: { tokens: Token<string>[] };
  zIndex: { tokens: Token<string>[] };
  shadow: { tokens: Token<Themed>[] };
};

const root = new URL('../packages/client/', import.meta.url);
const tokens = JSON.parse(readFileSync(new URL('tokens.json', root), 'utf8')) as Tokens;

const declare = (name: string, value: string) => `  --${name}: ${value};`;
const themedTokens = [...tokens.color.tokens, ...tokens.shadow.tokens];
const dark = themedTokens.map((t) => declare(t.name, t.value.dark));
// Board, highlight and quality colours are the same in both themes; light restates only the rest.
const light = themedTokens
  .filter((t) => t.value.light !== t.value.dark)
  .map((t) => `  ${declare(t.name, t.value.light)}`);

const fixed = [
  // Single quotes, as Prettier wants them.
  ...Object.entries(tokens.type.families).map(([name, value]) =>
    declare(`font-${name}`, value.replaceAll('"', "'")),
  ),
  ...tokens.type.groups.flatMap((group) =>
    group.styles.map((s) =>
      declare(
        `text-${s.name}`,
        `${s.fontWeight} ${s.fontSize} / ${s.lineHeight} var(--font-${group.family})`,
      ),
    ),
  ),
  ...[tokens.spacing, tokens.radius, tokens.size, tokens.zIndex].flatMap((g) =>
    g.tokens.map((t) => declare(t.name, t.value)),
  ),
];

// Dark is the primary theme, so it is also what a browser without a preference gets.
const css = `/* Generated by scripts/tokens-to-css.ts from packages/client/tokens.json; do not edit. */

:root {
  color-scheme: dark;
${dark.join('\n')}
${fixed.join('\n')}
}

@media (prefers-color-scheme: light) {
  :root {
    color-scheme: light;
${light.join('\n')}
  }
}
`;

writeFileSync(new URL('src/tokens.css', root), css);
